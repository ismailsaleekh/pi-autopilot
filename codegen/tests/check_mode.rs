#[test]
fn host_runtime_generation_and_mutations_fail_loudly() {
    let temp = fixture();
    codegen_command()
        .current_dir(temp.path())
        .assert()
        .success();
    let generated = fs::read_to_string(temp.path().join("src/generated/host-runtime-tables.ts"))
        .expect("read host runtime tables");
    assert!(generated.contains("HOST_COMMANDS"));
    assert!(generated.contains("OPENAI_API_KEY"));
    assert!(generated.contains("spawn-wave"));
    assert!(generated.contains("id-json-object"));
    assert!(generated.contains("question_id"));
    fs::write(
        temp.path().join("src/generated/host-runtime-tables.ts"),
        format!("{generated}\n// drift\n"),
    )
    .expect("mutate generated");
    codegen_command()
        .current_dir(temp.path())
        .arg("--check")
        .assert()
        .code(1)
        .stderr(predicate::str::contains("host-runtime-tables.ts"));

    for (label, from, to, expected) in [
        (
            "missing env",
            "env_deny \"OPENAI_API_KEY\"\n",
            "",
            "missing env deny OPENAI_API_KEY",
        ),
        (
            "bad env",
            "env_deny \"OPENAI_API_KEY\"",
            "env_deny \"OpenAI_API_KEY\"",
            "malformed env name",
        ),
        (
            "bad max",
            "effect \"spawn-wave\" operator_level_default=\"info\" fail_closed=#false acknowledge=#true max_items=64",
            "effect \"spawn-wave\" operator_level_default=\"info\" fail_closed=#false acknowledge=#true max_items=63",
            "spawn-wave max drift",
        ),
        (
            "bad effect",
            "effect \"done\" operator_level_default=\"info\" fail_closed=#false acknowledge=#false",
            "effect \"mystery\" operator_level_default=\"info\" fail_closed=#false acknowledge=#false",
            "effect/seam drift",
        ),
        (
            "bad adapter",
            "adapter=\"id-json-object\"",
            "adapter=\"raw\"",
            "operator-answer adapter/payload drift",
        ),
        (
            "bad payload",
            "payload=\"HostToCoreOperatorAnswerPayload\"",
            "payload=\"HostToCoreCommandPayload\"",
            "command payload drift",
        ),
    ] {
        let temp = fixture();
        let path = temp.path().join("data/host-runtime.kdl");
        let content = fs::read_to_string(&path).expect("read host runtime");
        fs::write(&path, content.replace(from, to))
            .unwrap_or_else(|error| panic!("write {label}: {error}"));
        codegen_command()
            .current_dir(temp.path())
            .assert()
            .code(2)
            .stderr(predicate::str::contains(expected));
    }
    let temp = fixture();
    let path = temp.path().join("data/contracts.kdl");
    fs::write(
        &path,
        fs::read_to_string(&path).unwrap().replace(
            "field \"question_id\" type=\"id\" required=#true",
            "field \"question_id\" type=\"string\" required=#true",
        ),
    )
    .unwrap();
    codegen_command()
        .current_dir(temp.path())
        .assert()
        .code(2)
        .stderr(predicate::str::contains(
            "operator-answer contract shape drift",
        ));
}

#[test]
fn seam_mutations_fail_loudly() {
    let cases = [
        (
            "missing route",
            "route kind=\"done\" direction=\"core-to-host\" posture=\"supported\" payload=\"CoreToHostDonePayload\" adapter=\"none\" effect=\"done\"\n",
            "contract frame without seam route",
        ),
        (
            "duplicate route",
            "route kind=\"command\" direction=\"host-to-core\" posture=\"supported\" payload=\"HostToCoreCommandPayload\" adapter=\"command\" effect=\"none\"\nroute kind=\"command\" direction=\"host-to-core\" posture=\"supported\" payload=\"HostToCoreCommandPayload\" adapter=\"command\" effect=\"none\"\n",
            "duplicate seam route `command`",
        ),
        (
            "unknown property",
            "route kind=\"command\" direction=\"host-to-core\" posture=\"supported\" payload=\"HostToCoreCommandPayload\" adapter=\"command\" effect=\"none\" surprise=\"no\"\n",
            "unknown property",
        ),
        (
            "contract without route",
            "",
            "contract frame without seam route",
        ),
        (
            "direction drift",
            "route kind=\"command\" direction=\"core-to-host\" posture=\"supported\" payload=\"HostToCoreCommandPayload\" adapter=\"none\" effect=\"command\"\n",
            "has no contract frame",
        ),
        (
            "payload drift",
            "route kind=\"command\" direction=\"host-to-core\" posture=\"supported\" payload=\"CoreToHostDonePayload\" adapter=\"command\" effect=\"none\"\n",
            "direction/payload drift",
        ),
        (
            "bad posture",
            "route kind=\"command\" direction=\"host-to-core\" posture=\"maybe\" payload=\"HostToCoreCommandPayload\" adapter=\"command\" effect=\"none\"\n",
            "invalid posture",
        ),
    ];
    for (label, content, expected) in cases {
        let temp = fixture();
        fs::write(
            temp.path().join("data/seam.kdl"),
            format!("schema \"autopilot.seam.v1\"\nversion 1\n{content}"),
        )
        .unwrap_or_else(|error| panic!("write {label}: {error}"));
        codegen_command()
            .current_dir(temp.path())
            .assert()
            .code(2)
            .stderr(predicate::str::contains(expected));
    }
}
