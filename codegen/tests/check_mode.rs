use std::fs;
use std::path::Path;

use assert_cmd::Command;
use predicates::prelude::*;
use tempfile::TempDir;

fn fixture() -> TempDir {
    let temp = tempfile::tempdir().expect("tempdir");
    let data_dir = temp.path().join("data");
    fs::create_dir_all(&data_dir).expect("create data dir");
    for name in [
        "contracts.kdl",
        "seam.kdl",
        "host-runtime.kdl",
        "pi-rpc.kdl",
    ] {
        fs::copy(
            Path::new(env!("CARGO_MANIFEST_DIR")).join(format!("../data/{name}")),
            data_dir.join(name),
        )
        .expect("copy data");
    }
    temp
}

fn codegen_command() -> Command {
    Command::cargo_bin("codegen").expect("codegen binary")
}

#[test]
fn check_catches_a_hand_edit_and_recovers() {
    let temp = fixture();

    codegen_command()
        .current_dir(temp.path())
        .assert()
        .success();
    codegen_command()
        .current_dir(temp.path())
        .arg("--check")
        .assert()
        .success();

    let generated = temp.path().join("drivers/src/generated/tables.rs");
    let mut content = fs::read_to_string(&generated).expect("read generated file");
    content.push_str("// hand edit\n");
    fs::write(&generated, content).expect("mutate generated file");

    codegen_command()
        .current_dir(temp.path())
        .arg("--check")
        .assert()
        .code(1)
        .stderr(predicates::str::contains("first differing line"));

    codegen_command()
        .current_dir(temp.path())
        .assert()
        .success();
    codegen_command()
        .current_dir(temp.path())
        .arg("--check")
        .assert()
        .success();
}

