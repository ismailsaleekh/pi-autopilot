use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use kdl::{KdlDocument, KdlEntry, KdlNode, KdlValue};
use serde_json::{Map as JsonMap, Value as JsonValue, json};
use sha2::{Digest as ShaDigest, Sha256};

const GENERATED_MARKER: &str = "@generated by codegen";

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("{error}");
            ExitCode::from(error.exit_code())
        }
    }
}

fn run() -> Result<(), CodegenError> {
    let mut check = false;
    for arg in std::env::args().skip(1) {
        if arg == "--check" {
            check = true;
        } else {
            return Err(CodegenError::Usage(format!("unknown argument: {arg}")));
        }
    }

    let source_path = Path::new("data/contracts.kdl");
    let source = std::fs::read_to_string(source_path).map_err(|error| {
        CodegenError::Input(format!("failed to read data/contracts.kdl: {error}"))
    })?;
    let contracts = Contracts::parse(&source)?;
    let outputs = emit_all(&contracts)?;

    if check {
        check_outputs(&outputs)
    } else {
        write_outputs(&outputs)
    }
}

#[derive(Debug)]
enum CodegenError {
    Usage(String),
    Input(String),
    Io(String),
    Drift(String),
}

impl CodegenError {
    fn exit_code(&self) -> u8 {
        match self {
            Self::Usage(_) => 64,
            Self::Input(_) => 2,
            Self::Io(_) | Self::Drift(_) => 1,
        }
    }
}

impl std::fmt::Display for CodegenError {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Usage(message)
            | Self::Input(message)
            | Self::Io(message)
            | Self::Drift(message) => {
                write!(formatter, "{message}")
            }
        }
    }
}

#[derive(Debug, Clone)]
struct Contracts {
    schema: String,
    version: u64,
    types: BTreeSet<String>,
    constants: BTreeMap<String, String>,
    artifacts: Vec<Artifact>,
    enums: Vec<EnumDef>,
    frames: Vec<Frame>,
}

#[derive(Debug, Clone)]
struct Artifact {
    name: String,
    schema: String,
    model_produced: bool,
    doc: String,
    admits: Option<String>,
    items: Vec<Item>,
}

#[derive(Debug, Clone)]
struct Frame {
    direction: String,
    kind: String,
    doc: String,
    items: Vec<Item>,
}

#[derive(Debug, Clone)]
struct EnumDef {
    name: String,
    values: Vec<String>,
    doc: Option<String>,
}

#[derive(Debug, Clone)]
enum Item {
    Field(Field),
    List(List),
    Group(Group),
    Record(Record),
}

#[derive(Debug, Clone)]
struct Field {
    name: String,
    type_id: String,
    required: bool,
    nullable: bool,
    doc: Option<String>,
}

#[derive(Debug, Clone)]
struct List {
    name: String,
    item_type: String,
    required: bool,
    nullable: bool,
    doc: Option<String>,
}

#[derive(Debug, Clone)]
struct Group {
    name: String,
    required: bool,
    items: Vec<Item>,
}

#[derive(Debug, Clone)]
struct Record {
    name: String,
    items: Vec<Item>,
}

impl Contracts {
    fn parse(source: &str) -> Result<Self, CodegenError> {
        let doc = source.parse::<KdlDocument>().map_err(|error| {
            CodegenError::Input(format!("failed to parse data/contracts.kdl: {error}"))
        })?;
        let mut schema = None;
        let mut version = None;
        let mut types = BTreeSet::new();
        let mut constants = BTreeMap::new();
        let mut artifacts = Vec::new();
        let mut enums = Vec::new();
        let mut frames = Vec::new();

        for node in doc.nodes() {
            match name(node) {
                "schema" => {
                    ensure_entries(node, 1, &[], source)?;
                    schema = Some(arg_string(node, 0, source)?.to_owned());
                    ensure_no_children(node, source)?;
                }
                "version" => {
                    ensure_entries(node, 1, &[], source)?;
                    version = Some(arg_u64(node, 0, source)?);
                    ensure_no_children(node, source)?;
                }
                "doc" => {
                    ensure_entries(node, 1, &[], source)?;
                    ensure_no_children(node, source)?;
                }
                "type" => {
                    ensure_entries(node, 1, &["doc"], source)?;
                    types.insert(arg_string(node, 0, source)?.to_owned());
                    prop_string_optional(node, "doc", source)?;
                    ensure_no_children(node, source)?;
                }
                "artifact" => artifacts.push(parse_artifact(node, source)?),
                "enum" => enums.push(parse_enum(node, source)?),
                "frame" => frames.push(parse_frame(node, source)?),
                "constant" => {
                    ensure_entries(node, 1, &["value", "doc"], source)?;
                    let key = arg_string(node, 0, source)?.to_owned();
                    let value = prop_string(node, "value", source)?.to_owned();
                    prop_string_optional(node, "doc", source)?;
                    ensure_no_children(node, source)?;
                    if constants.insert(key.clone(), value).is_some() {
                        return Err(CodegenError::Input(format!(
                            "duplicate constant `{key}` at line {}",
                            line_of(node, source)
                        )));
                    }
                }
                "artifact_category" => {
                    ensure_entries(node, 1, &["path", "doc"], source)?;
                    arg_string(node, 0, source)?;
                    prop_string(node, "path", source)?;
                    prop_string_optional(node, "doc", source)?;
                    ensure_no_children(node, source)?;
                }
                "resource_gate" => {
                    ensure_entries(
                        node,
                        1,
                        &["default", "counts", "doc", "value", "threshold", "effect"],
                        source,
                    )?;
                    arg_string(node, 0, source)?;
                    for key in ["default", "counts", "doc", "value", "threshold", "effect"] {
                        prop_string_optional(node, key, source)?;
                    }
                    ensure_no_children(node, source)?;
                }
                "scheduler_order" => {
                    ensure_entries(node, 1, &["key", "direction"], source)?;
                    arg_u64(node, 0, source)?;
                    prop_string(node, "key", source)?;
                    prop_string(node, "direction", source)?;
                    ensure_no_children(node, source)?;
                }
                other => {
                    return Err(CodegenError::Input(format!(
                        "unknown top-level node `{other}` at line {}",
                        line_of(node, source)
                    )));
                }
            }
        }

        let schema = schema.ok_or_else(|| {
            CodegenError::Input("missing required top-level schema node".to_owned())
        })?;
        let version = version.ok_or_else(|| {
            CodegenError::Input("missing required top-level version node".to_owned())
        })?;
        let contracts = Self {
            schema,
            version,
            types,
            constants,
            artifacts,
            enums,
            frames,
        };
        contracts.validate_types()?;
        Ok(contracts)
    }

    fn validate_types(&self) -> Result<(), CodegenError> {
        let mut known = builtin_scalar_types();
        known.extend(self.types.iter().cloned());
        known.extend(self.enums.iter().map(|entry| entry.name.clone()));
        known.extend(self.artifacts.iter().map(|entry| entry.name.clone()));
        for artifact in &self.artifacts {
            collect_record_names(&artifact.items, &mut known);
        }

        for artifact in &self.artifacts {
            validate_item_types(
                &artifact.items,
                &known,
                &format!("artifact `{}`", artifact.name),
            )?;
        }
        for frame in &self.frames {
            validate_item_types(&frame.items, &known, &format!("frame `{}`", frame.kind))?;
        }
        Ok(())
    }
}

