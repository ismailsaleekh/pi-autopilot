#!/usr/bin/env node
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const PACKAGE_ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
export const GENERATED_MARKER = '<!-- @generated by docs-generate -->';

const SOURCE_PATHS = {
  contracts: 'data/contracts.kdl',
  workflow: 'data/workflow.kdl',
  roles: 'data/roles.kdl',
  roster: 'data/roster.kdl',
  boundaries: 'data/boundary-modes.kdl',
};

const OUTPUT_PATHS = {
  index: 'docs/generated/index.md',
  contracts: 'docs/generated/contracts.md',
  workflow: 'docs/generated/workflow.md',
  roles: 'docs/generated/roles.md',
  roster: 'docs/generated/roster.md',
  boundaries: 'docs/generated/boundaries.md',
};

const ALLOWED_NODES = {
  contracts: new Set(['schema', 'version', 'doc', 'type', 'artifact', 'field', 'list', 'group', 'record', 'enum', 'value', 'frame', 'constant', 'pattern', 'admits', 'artifact_category', 'resource_gate', 'scheduler_order']),
  workflow: new Set(['schema', 'version', 'doc', 'machine', 'initial', 'state', 'transition', 'axis', 'value', 'attribute', 'verdict_set', 'total_verdicts', 'capacity_class']),
  roles: new Set(['role', 'schema', 'version', 'modes', 'mode_parameters', 'model_slot', 'thinking', 'tools', 'repository', 'git', 'network', 'package_state', 'operator_checkout', 'context_policy', 'result_contract', 'checkpoint_contract', 'terminal_path', 'boundary_prompts']),
  roster: new Set(['slot', 'provider', 'model', 'thinking', 'route', 'roles']),
  boundaries: new Set(['schema', 'version', 'boundary']),
};

export function usage(exitCode = 2) {
  const stream = exitCode === 0 ? process.stdout : process.stderr;
  stream.write('Usage: node scripts/docs-generate.mjs\n');
  process.exit(exitCode);
}

function scalarText(value) {
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  return String(value);
}

function parseQuoted(token, location) {
  try {
    return JSON.parse(token);
  } catch (error) {
    throw sourceError(location, `invalid quoted scalar ${token}: ${error.message}`);
  }
}

function sourceError(location, message) {
  const error = new Error(`${location}: ${message}`);
  error.sourceMissing = false;
  return error;
}

function parseValue(rest, location) {
  if (rest.startsWith('"')) {
    const match = rest.match(/^"(?:[^"\\]|\\.)*"/u);
    if (!match) throw sourceError(location, 'unterminated quoted scalar');
    return { value: parseQuoted(match[0], location), rest: rest.slice(match[0].length) };
  }
  if (rest.startsWith('#true')) return { value: true, rest: rest.slice(5) };
  if (rest.startsWith('#false')) return { value: false, rest: rest.slice(6) };
  const number = rest.match(/^[0-9]+\b/u);
  if (number) return { value: Number(number[0]), rest: rest.slice(number[0].length) };
  throw sourceError(location, `unsupported scalar near ${JSON.stringify(rest.slice(0, 40))}`);
}

function parseNodeLine(trimmed, location) {
  let text = trimmed;
  let opens = false;
  if (text.endsWith('{')) {
    opens = true;
    text = text.slice(0, -1).trimEnd();
  }
  const nameMatch = text.match(/^([A-Za-z_][A-Za-z0-9_-]*)\b/u);
  if (!nameMatch) throw sourceError(location, `malformed node line ${JSON.stringify(trimmed)}`);
  const name = nameMatch[1];
  let rest = text.slice(name.length);
  const args = [];
  const props = new Map();
  while (rest.trim().length > 0) {
    rest = rest.trimStart();
    const prop = rest.match(/^([A-Za-z_][A-Za-z0-9_-]*)=/u);
    if (prop) {
      const key = prop[1];
      if (props.has(key)) throw sourceError(location, `duplicate property ${key} on ${name}`);
      const parsed = parseValue(rest.slice(prop[0].length), location);
      props.set(key, parsed.value);
      rest = parsed.rest;
    } else {
      const parsed = parseValue(rest, location);
      args.push(parsed.value);
      rest = parsed.rest;
    }
  }
  return { name, args, props: Object.fromEntries(props), opens };
}

function loadSource(kind) {
  const rel = SOURCE_PATHS[kind];
  const abs = resolve(PACKAGE_ROOT, rel);
  if (!existsSync(abs)) {
    const error = new Error(`required source is missing: ${rel}`);
    error.sourceMissing = true;
    throw error;
  }
  return readFileSync(abs, 'utf8');
}

function parseKdl(kind, text) {
  const allowed = ALLOWED_NODES[kind];
  const nodes = [];
  const stack = [];
  const lines = text.split(/\r?\n/u);
  for (let i = 0; i < lines.length; i += 1) {
    const lineNo = i + 1;
    const raw = lines[i];
    const trimmed = raw.trim();
    if (trimmed === '' || trimmed.startsWith('//')) continue;
    const location = `${SOURCE_PATHS[kind]}:${lineNo}`;
    if (trimmed === '}') {
      if (stack.length === 0) throw sourceError(location, 'unexpected closing brace');
      stack.pop();
      continue;
    }
    if (trimmed.includes('}')) throw sourceError(location, 'closing brace must be on its own line in this strict subset');
    const node = parseNodeLine(trimmed, location);
    if (!allowed.has(node.name)) throw sourceError(location, `unknown node ${node.name}`);
    node.line = lineNo;
    node.depth = stack.length;
    node.parent = stack.at(-1)?.name ?? null;
    nodes.push(node);
    if (node.opens) stack.push(node);
  }
  if (stack.length !== 0) throw sourceError(SOURCE_PATHS[kind], `unclosed node ${stack.at(-1).name} from line ${stack.at(-1).line}`);
  return nodes;
}

function requireArgs(node, count, kind) {
  if (node.args.length !== count) throw sourceError(`${kind}:${node.line}`, `${node.name} requires ${count} positional argument(s), got ${node.args.length}`);
}

function requireProp(node, key, kind) {
  if (!Object.prototype.hasOwnProperty.call(node.props, key)) throw sourceError(`${kind}:${node.line}`, `${node.name} missing required property ${key}`);
  return node.props[key];
}

function parseContracts() {
  const nodes = parseKdl('contracts', loadSource('contracts'));
  const artifacts = [];
  const enums = [];
  const frames = [];
  const types = [];
  let currentArtifact = null;
  let currentEnum = null;
  let currentFrame = null;
  const context = [];
  for (const node of nodes) {
    if (node.depth === 0) {
      currentArtifact = null;
      currentEnum = null;
      currentFrame = null;
    }
    if (node.name === 'type') {
      requireArgs(node, 1, 'contracts');
      types.push({ name: node.args[0], doc: node.props.doc ?? '' });
    } else if (node.name === 'artifact') {
      requireArgs(node, 1, 'contracts');
      const artifact = { name: node.args[0], schema: requireProp(node, 'schema', 'contracts'), producer: requireProp(node, 'producer', 'contracts'), modelProduced: scalarText(requireProp(node, 'model_produced', 'contracts')), doc: '', admits: [], fields: [] };
      artifacts.push(artifact);
      currentArtifact = artifact;
    } else if (node.name === 'enum') {
      requireArgs(node, 1, 'contracts');
      const entry = { name: node.args[0], values: [] };
      enums.push(entry);
      currentEnum = entry;
    } else if (node.name === 'frame') {
      const entry = { direction: requireProp(node, 'direction', 'contracts'), kind: requireProp(node, 'kind', 'contracts'), fields: [] };
      frames.push(entry);
      currentFrame = entry;
    } else if (node.name === 'doc' && node.depth === 1 && currentArtifact) {
      requireArgs(node, 1, 'contracts');
      currentArtifact.doc = node.args[0];
    } else if (node.name === 'admits' && currentArtifact) {
      requireArgs(node, 1, 'contracts');
      currentArtifact.admits.push(node.args[0]);
    } else if ((node.name === 'field' || node.name === 'list') && currentArtifact) {
      requireArgs(node, 1, 'contracts');
      const type = node.name === 'list' ? requireProp(node, 'item', 'contracts') : requireProp(node, 'type', 'contracts');
      const path = [...context.slice(0, node.depth - 1), node.args[0]].join('.');
      currentArtifact.fields.push({ shape: node.name, name: path, type, required: scalarText(node.props.required ?? ''), nullable: scalarText(node.props.nullable ?? ''), doc: node.props.doc ?? '' });
      if (currentFrame && node.depth === 1) currentFrame.fields.push(`${node.name} ${node.args[0]}:${type}`);
    } else if ((node.name === 'group' || node.name === 'record') && currentArtifact) {
      requireArgs(node, 1, 'contracts');
      context[node.depth - 1] = node.args[0];
      context.length = node.depth;
    } else if (node.name === 'value' && currentEnum) {
      requireArgs(node, 1, 'contracts');
      currentEnum.values.push(node.args[0]);
    }
  }
  return { artifacts, enums, frames, types };
}

function parseWorkflow() {
  const nodes = parseKdl('workflow', loadSource('workflow'));
  const machines = [];
  const axes = [];
  const verdictSets = [];
  const attributes = [];
  const totals = [];
  const capacities = [];
  let machine = null;
  let axis = null;
  let verdictSet = null;
  let capacity = null;
  for (const node of nodes) {
    if (node.depth === 0) {
      machine = null;
      axis = null;
      verdictSet = null;
      capacity = null;
    }
    if (node.name === 'machine') {
      requireArgs(node, 1, 'workflow');
      machine = { name: node.args[0], doc: '', initial: '', states: [], transitions: [] };
      machines.push(machine);
    } else if (node.name === 'doc' && machine && node.depth === 1) {
      requireArgs(node, 1, 'workflow');
      machine.doc = node.args[0];
    } else if (node.name === 'initial' && machine) {
      requireArgs(node, 1, 'workflow');
      machine.initial = node.args[0];
    } else if (node.name === 'state' && machine) {
      requireArgs(node, 1, 'workflow');
      machine.states.push({ name: node.args[0], terminal: scalarText(requireProp(node, 'terminal', 'workflow')), flags: Object.entries(node.props).filter(([key]) => key !== 'terminal').map(([key, value]) => `${key}=${scalarText(value)}`) });
    } else if (node.name === 'transition' && machine) {
      machine.transitions.push({ from: requireProp(node, 'from', 'workflow'), to: requireProp(node, 'to', 'workflow'), evidence: requireProp(node, 'evidence', 'workflow'), verdict: node.props.verdict ?? '', route: node.props.route ?? '' });
    } else if (node.name === 'axis') {
      requireArgs(node, 1, 'workflow');
      axis = { name: node.args[0], contract: requireProp(node, 'contract', 'workflow'), values: [] };
      axes.push(axis);
    } else if (node.name === 'value' && axis) {
      requireArgs(node, 1, 'workflow');
      axis.values.push(node.args[0]);
    } else if (node.name === 'attribute') {
      requireArgs(node, 1, 'workflow');
      attributes.push({ name: node.args[0], contract: requireProp(node, 'contract', 'workflow'), doc: node.props.doc ?? '' });
    } else if (node.name === 'verdict_set') {
      requireArgs(node, 1, 'workflow');
      verdictSet = { name: node.args[0], contract: requireProp(node, 'contract', 'workflow'), values: [] };
      verdictSets.push(verdictSet);
    } else if (node.name === 'value' && verdictSet) {
      requireArgs(node, 1, 'workflow');
      verdictSet.values.push(node.args[0]);
    } else if (node.name === 'total_verdicts') {
      totals.push({ machine: requireProp(node, 'machine', 'workflow'), kind: requireProp(node, 'kind', 'workflow'), from: requireProp(node, 'from', 'workflow'), doc: node.props.doc ?? '' });
    } else if (node.name === 'capacity_class') {
      requireArgs(node, 1, 'workflow');
      capacity = { name: node.args[0], gate: requireProp(node, 'gate', 'workflow'), states: [] };
      capacities.push(capacity);
    } else if (node.name === 'state' && capacity) {
      requireArgs(node, 1, 'workflow');
      capacity.states.push(node.args[0]);
    }
  }
  return { machines, axes, verdictSets, attributes, totals, capacities };
}

function parseRoles() {
  const nodes = parseKdl('roles', loadSource('roles'));
  const roles = [];
  let role = null;
  for (const node of nodes) {
    if (node.name === 'role') {
      requireArgs(node, 1, 'roles');
      role = { id: node.args[0] };
      roles.push(role);
    } else if (role && node.depth === 1) {
      if (node.args.length === 0) throw sourceError(`roles:${node.line}`, `${node.name} requires at least one value`);
      role[node.name] = node.args.map(scalarText);
    }
  }
  validateRoleFiles(roles);
  return roles;
}

function firstHeading(path) {
  const text = readFileSync(resolve(PACKAGE_ROOT, path), 'utf8');
  const match = text.match(/^##\s+(.+)$/mu);
  if (!match) throw sourceError(path, 'role markdown must contain at least one H2 heading');
  return match[1];
}

function validateRoleFiles(roles) {
  const roleIds = new Set(roles.map((role) => role.id));
  const rolesRoot = resolve(PACKAGE_ROOT, 'roles');
  if (!existsSync(rolesRoot)) throw sourceError('roles/', 'roles directory is missing');
  for (const role of roles) {
    const base = `roles/${role.id}/base.md`;
    if (!existsSync(resolve(PACKAGE_ROOT, base))) throw sourceError(base, 'registered role base file is missing');
    role.base_heading = firstHeading(base);
    const modes = role.modes ?? [];
    role.mode_files = [];
    for (const mode of modes) {
      const modePath = `roles/${role.id}/modes/${mode}.md`;
      if (!existsSync(resolve(PACKAGE_ROOT, modePath))) throw sourceError(modePath, 'registered role mode file is missing');
      role.mode_files.push({ mode, path: modePath, heading: firstHeading(modePath) });
    }
  }
  for (const entry of readdirSync(rolesRoot, { withFileTypes: true })) {
    if (entry.isDirectory() && !roleIds.has(entry.name)) throw sourceError(`roles/${entry.name}/`, 'role directory is not registered in data/roles.kdl');
  }
}

function parseRoster() {
  const nodes = parseKdl('roster', loadSource('roster'));
  const slots = [];
  let slot = null;
  for (const node of nodes) {
    if (node.name === 'slot') {
      requireArgs(node, 1, 'roster');
      slot = { id: node.args[0] };
      slots.push(slot);
    } else if (slot && node.depth === 1) {
      if (node.args.length === 0) throw sourceError(`roster:${node.line}`, `${node.name} requires at least one value`);
      slot[node.name] = node.args.map(scalarText);
    }
  }
  if (slots.length !== 5) throw sourceError('data/roster.kdl', `expected five roster slots, got ${slots.length}`);
  return slots;
}

function parseBoundaries() {
  const nodes = parseKdl('boundaries', loadSource('boundaries'));
  return nodes.filter((node) => node.name === 'boundary').map((node) => {
    requireArgs(node, 1, 'boundaries');
    return { id: node.args[0], mode: requireProp(node, 'mode', 'boundaries'), reason: requireProp(node, 'reason', 'boundaries') };
  });
}

function esc(value) {
  return String(value ?? '').replace(/\|/gu, '\\|').replace(/\n/gu, '<br>');
}

function table(headers, rows) {
  return [`| ${headers.join(' | ')} |`, `| ${headers.map(() => '---').join(' | ')} |`, ...rows.map((row) => `| ${row.map(esc).join(' | ')} |`)].join('\n');
}

function docHeader(title, sources) {
  return `${GENERATED_MARKER}\n\n# ${title}\n\nSources: ${sources.map((source) => `\`${source}\``).join(', ')}.\n\n`;
}

function renderContracts(model) {
  const artifactRows = model.artifacts.map((artifact) => [artifact.name, artifact.schema, artifact.producer, artifact.modelProduced, artifact.doc]);
  const fieldRows = model.artifacts.flatMap((artifact) => artifact.fields.map((field) => [artifact.name, field.shape, field.name, field.type, field.required, field.nullable, field.doc]));
  const enumRows = model.enums.map((entry) => [entry.name, entry.values.join(', ')]);
  const frameRows = model.frames.map((frame) => [frame.kind, frame.direction, frame.fields.join('; ')]);
  return `${docHeader('Generated artifact contracts', [SOURCE_PATHS.contracts])}## Artifacts\n\n${table(['Artifact', 'Schema', 'Producer', 'Model produced', 'Doc'], artifactRows)}\n\n## Fields and lists\n\n${table(['Artifact', 'Shape', 'Path', 'Type/item', 'Required', 'Nullable', 'Doc'], fieldRows)}\n\n## Enums\n\n${table(['Enum', 'Values'], enumRows)}\n\n## Seam frames\n\n${table(['Kind', 'Direction', 'Fields'], frameRows)}\n`;
}

function renderWorkflow(model) {
  const machineRows = model.machines.map((machine) => [machine.name, machine.initial, machine.states.length, machine.transitions.length, machine.doc]);
  const stateRows = model.machines.flatMap((machine) => machine.states.map((state) => [machine.name, state.name, state.terminal, state.flags.join(', ')]));
  const transitionRows = model.machines.flatMap((machine) => machine.transitions.map((transition) => [machine.name, transition.from, transition.to, transition.evidence, transition.verdict, transition.route]));
  const verdictRows = model.verdictSets.map((set) => [set.name, set.contract, set.values.join(', ')]);
  return `${docHeader('Generated workflow state machines', [SOURCE_PATHS.workflow])}## Machines\n\n${table(['Machine', 'Initial', 'States', 'Transitions', 'Doc'], machineRows)}\n\n## States\n\n${table(['Machine', 'State', 'Terminal', 'Flags'], stateRows)}\n\n## Transitions\n\n${table(['Machine', 'From', 'To', 'Evidence', 'Verdict', 'Route'], transitionRows)}\n\n## Verdict sets\n\n${table(['Kind', 'Contract', 'Values'], verdictRows)}\n`;
}

function renderRoles(roles) {
  const roleRows = roles.map((role) => [role.id, role.model_slot?.join(', '), role.thinking?.join(', '), role.modes?.join(', '), role.tools?.join(', '), role.terminal_path?.join(', ')]);
  const fileRows = roles.flatMap((role) => [[role.id, 'base', `roles/${role.id}/base.md`, role.base_heading], ...role.mode_files.map((file) => [role.id, file.mode, file.path, file.heading])]);
  return `${docHeader('Generated role registry', [SOURCE_PATHS.roles, 'roles/**'])}## Registry\n\n${table(['Role', 'Model slot', 'Thinking', 'Modes', 'Tools', 'Terminal path'], roleRows)}\n\n## Role files\n\n${table(['Role', 'Mode', 'Path', 'First H2'], fileRows)}\n`;
}

function renderRoster(slots) {
  const rows = slots.map((slot) => [slot.id, slot.provider?.join(', '), slot.model?.join(', '), slot.thinking?.join(', '), slot.route?.join(', '), slot.roles?.join(', ')]);
  return `${docHeader('Generated model roster', [SOURCE_PATHS.roster])}The roster contains exactly five subscription-route slots.\n\n${table(['Slot', 'Provider', 'Model', 'Thinking', 'Route', 'Roles'], rows)}\n`;
}

function renderBoundaries(boundaries) {
  return `${docHeader('Generated boundary registry', [SOURCE_PATHS.boundaries])}${table(['Boundary', 'Mode', 'Reason'], boundaries.map((boundary) => [boundary.id, boundary.mode, boundary.reason]))}\n`;
}

function renderIndex(outputs) {
  const rows = Object.entries(outputs).filter(([key]) => key !== 'index').map(([key, path]) => [key, path]);
  return `${docHeader('Generated architecture docs index', Object.values(SOURCE_PATHS))}These files are regenerated from the current Rust-Core/TypeScript-Host architecture authorities.\n\n${table(['Area', 'Generated file'], rows)}\n`;
}

export function renderGeneratedDocs() {
  const contracts = parseContracts();
  const workflow = parseWorkflow();
  const roles = parseRoles();
  const roster = parseRoster();
  const boundaries = parseBoundaries();
  return new Map([
    [OUTPUT_PATHS.index, renderIndex(OUTPUT_PATHS)],
    [OUTPUT_PATHS.contracts, renderContracts(contracts)],
    [OUTPUT_PATHS.workflow, renderWorkflow(workflow)],
    [OUTPUT_PATHS.roles, renderRoles(roles)],
    [OUTPUT_PATHS.roster, renderRoster(roster)],
    [OUTPUT_PATHS.boundaries, renderBoundaries(boundaries)],
  ]);
}

export function writeGeneratedDocs() {
  const rendered = renderGeneratedDocs();
  for (const [rel, text] of rendered) {
    const abs = resolve(PACKAGE_ROOT, rel);
    mkdirSync(resolve(abs, '..'), { recursive: true });
    writeFileSync(abs, text, 'utf8');
    process.stdout.write(`emitted ${rel}\n`);
  }
  return rendered;
}

function main() {
  const args = process.argv.slice(2);
  if (args.length !== 0) {
    if (args.length === 1 && (args[0] === '--help' || args[0] === '-h')) usage(0);
    usage(2);
  }
  writeGeneratedDocs();
}

if (process.argv[1] && basename(process.argv[1]) === 'docs-generate.mjs') {
  try {
    main();
  } catch (error) {
    process.stderr.write(`docs-generate: ${error.message}\n`);
    process.exitCode = error.sourceMissing ? 2 : 2;
  }
}
