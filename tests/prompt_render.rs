fn assert_prompt_matches_contract_admits(root: &Path, rendered: &str) -> Result<(), String> {
    prompt_matches_contract_admits(root, rendered)
}

fn prompt_matches_contract_admits(root: &Path, rendered: &str) -> Result<(), String> {
    let contract_prompt = contract_prompt_from_source(root, BOUNDARY_PROMPT)?;
    if !rendered.contains(&contract_prompt.admits) {
        return Err(format!(
            "{BOUNDARY_PROMPT} rendered prompt is missing data/contracts.kdl admits text"
        ));
    }
    let actual = rendered_boundary_prompt(rendered, BOUNDARY_PROMPT)?;
    if actual == contract_prompt.markdown {
        Ok(())
    } else {
        Err(format!(
            "{BOUNDARY_PROMPT} rendered prompt block does not match data/contracts.kdl admits"
        ))
    }
}

struct ContractPrompt {
    admits: String,
    markdown: String,
}

fn contract_prompt_from_source(root: &Path, name: &str) -> Result<ContractPrompt, String> {
    let path = root.join("data/contracts.kdl");
    let source = fs::read_to_string(&path)
        .map_err(|error| format!("failed to read {}: {error}", path.display()))?;
    let admits = artifact_admits(&source, name)?;
    Ok(ContractPrompt {
        markdown: format!("<!-- @generated by codegen -->\n# {name}\n\n{admits}\n"),
        admits,
    })
}

fn artifact_admits(source: &str, artifact_name: &str) -> Result<String, String> {
    let artifact = format!("artifact \"{artifact_name}\"");
    let artifact_start = source
        .find(&artifact)
        .ok_or_else(|| format!("missing {artifact_name} artifact in data/contracts.kdl"))?;
    let after_artifact = &source[artifact_start + artifact.len()..];
    let open_offset = after_artifact
        .find('{')
        .ok_or_else(|| format!("{artifact_name} artifact has no child block"))?;
    let open_index = artifact_start + artifact.len() + open_offset;
    let close_index = matching_brace(source, open_index)
        .ok_or_else(|| format!("{artifact_name} artifact block is not closed"))?;
    let block = &source[open_index + 1..close_index];
    let admits_start = block
        .find("admits")
        .ok_or_else(|| format!("{artifact_name} artifact has no admits node"))?;
    parse_quoted_kdl_string(&block[admits_start + "admits".len()..])
        .map_err(|error| format!("{artifact_name} admits parse failed: {error}"))
}

fn matching_brace(source: &str, open_index: usize) -> Option<usize> {
    let mut depth = 0usize;
    let mut in_string = false;
    let mut escaped = false;
    for (offset, character) in source[open_index..].char_indices() {
        let index = open_index + offset;
        if in_string {
            if escaped {
                escaped = false;
            } else if character == '\\' {
                escaped = true;
            } else if character == '"' {
                in_string = false;
            }
            continue;
        }
        match character {
            '"' => in_string = true,
            '{' => depth += 1,
            '}' => {
                depth = depth.checked_sub(1)?;
                if depth == 0 {
                    return Some(index);
                }
            }
            _ => {}
        }
    }
    None
}

fn parse_quoted_kdl_string(text: &str) -> Result<String, String> {
    let quoted = text
        .trim_start()
        .strip_prefix('"')
        .ok_or_else(|| "expected quoted string".to_owned())?;
    let mut value = String::new();
    let mut escaped = false;
    for character in quoted.chars() {
        if escaped {
            value.push(match character {
                'n' => '\n',
                'r' => '\r',
                't' => '\t',
                '"' => '"',
                '\\' => '\\',
                other => other,
            });
            escaped = false;
        } else if character == '\\' {
            escaped = true;
        } else if character == '"' {
            return Ok(value);
        } else {
            value.push(character);
        }
    }
    Err("unterminated quoted string".to_owned())
}

fn rendered_boundary_prompt<'a>(rendered: &'a str, name: &str) -> Result<&'a str, String> {
    let header = format!("#### {name}\n\n");
    let start = rendered
        .find(&header)
        .ok_or_else(|| format!("rendered prompt missing {name} boundary header"))?
        + header.len();
    let tail = &rendered[start..];
    let end = [tail.find("\n#### "), tail.find("\n\n## Layer ")]
        .into_iter()
        .flatten()
        .min()
        .ok_or_else(|| format!("rendered prompt missing end of {name} boundary block"))?;
    Ok(&tail[..end])
}

fn copy_prompt_fixture_root() -> Result<PathBuf, String> {
    let package = package_root();
    let temp = std::env::temp_dir().join(format!(
        "pi-autopilot-prompt-render-{}-{}",
        std::process::id(),
        TEMP_COUNTER.fetch_add(1, Ordering::Relaxed)
    ));
    match fs::remove_dir_all(&temp) {
        Ok(()) => {}
        Err(error) if error.kind() == ErrorKind::NotFound => {}
        Err(error) => return Err(format!("failed to remove {}: {error}", temp.display())),
    }
    for relative in [
        "data/contracts.kdl",
        "doctrine/global.md",
        "roles/validator/base.md",
        "roles/validator/modes/forward-release.md",
        "generated/prompts/validation_verdict.md",
        "generated/prompts/finding.md",
    ] {
        copy_fixture_file(&package, &temp, relative)?;
    }
    Ok(temp)
}

fn copy_fixture_file(package: &Path, temp: &Path, relative: &str) -> Result<(), String> {
    let destination = temp.join(relative);
    let parent = destination
        .parent()
        .ok_or_else(|| format!("{} has no parent", destination.display()))?;
    fs::create_dir_all(parent)
        .map_err(|error| format!("failed to create {}: {error}", parent.display()))?;
    fs::copy(package.join(relative), &destination)
        .map(|_| ())
        .map_err(|error| format!("failed to copy {relative}: {error}"))
}

fn package_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("..")
}

fn assert_in_order(text: &str, needles: &[&str]) {
    let mut position = 0;
    for needle in needles {
        let found = text[position..].find(needle).expect("needle found") + position;
        assert!(found >= position);
        position = found;
    }
}
